def mp(val,table):
    def f(m):
        h=m.group(0).lower()
        return table.get(h,m.group(0))
    return re.sub(r'#[0-9a-fA-F]{3,6}\b',f,val)
BGP=re.compile(r'^(background|background-color|background-image|border|border-top|border-bottom|border-left|border-right|border-color|outline|border-top-color|border-bottom-color)$')
TEXT_ONLY=False
def conv(decls):
    out=[]
    for d in decls:
        if ':' not in d: continue
        k,v=d.split(':',1); k=k.strip(); v=v.strip().replace('!important','').strip()
        if TEXT_ONLY and k not in('color','fill','stroke'): continue
        if k=='background' or k=='background-color' or k=='background-image': nv=mp(v,BG)
        elif BGP.match(k): nv=mp(v,BORD)
        elif k in('color','fill','stroke'): nv=mp(v,FG)
        else: continue
        if nv!=v: out.append('%s:%s!important'%(k,nv))
    return out
def pre(sel):
    r=[]
    for s in sel.split(','):
        s=s.strip()
        if not s: continue
        if s.startswith('html'): r.append('html[data-theme="dark"]'+s[4:])
        elif s.startswith(':root'): continue
        else: r.append('html[data-theme="dark"] '+s)
    return ','.join(r)
def walk(text):
    res=[]; i=0
    while i<len(text):
        j=text.find('{',i)
        if j<0: break
        head=text[i:j].strip()
        # find matching brace
        d=1;k=j+1
        while k<len(text) and d:
            if text[k]=='{': d+=1
            elif text[k]=='}': d-=1
            k+=1
        body=text[j+1:k-1]
        if head.startswith('@media') and 'prefers-color-scheme' in head: pass
        elif head.startswith('@media'):
            inner=walk(body)
            if inner: res.append(head+'{'+''.join(inner)+'}')
        elif head.startswith('@'): pass
        else:
            c=conv([x for x in re.split(r';(?![^()]*\))',body) if x.strip()])
            if c and pre(head): res.append(pre(head)+'{'+';'.join(c)+'}')
        i=k
    return res
